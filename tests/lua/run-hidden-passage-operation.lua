local Operation = dofile("src/missions/operation-hidden-passage/operation.lua")
local count = 0
local function test(name, fn)
  local ok, err = pcall(fn)
  assert(ok, name .. ": " .. tostring(err))
  count = count + 1
end
local function aboard()
  local objective = Operation.new("party-1", 3)
  assert(objective:lock_carrier(101))
  assert(objective:begin_boarding(101))
  assert(objective:boarded(101, "party-1", 3))
  return objective
end
test("uncollected party cannot complete", function()
  local o = Operation.new("party-1", 3)
  o:lock_carrier(101)
  assert(not o:deployed(101, "party-2", 3, true, true))
  assert(o.phase == "waiting")
end)
test("boarding is not completion", function()
  local o = Operation.new("party-1", 3)
  o:lock_carrier(101)
  o:begin_boarding(101)
  assert(not o:deployed(101, "party-2", 3, true, true))
  assert(o.phase == "boarding")
end)
test("full collection and landed delivery succeeds once", function()
  local o = aboard()
  assert(o:deployed(101, "party-2", 3, true, true))
  assert(o.phase == "complete")
  assert(not o:deployed(101, "party-2", 3, true, true))
  assert(not o:fail("late death") and o.phase == "complete")
end)
test("wrong-location drop can be recovered", function()
  local o = aboard()
  assert(not o:deployed(101, "party-2", 3, false, true))
  assert(o.phase == "waiting" and o.party_key == "party-2")
  assert(o:begin_boarding(101))
  assert(not o:boarded(101, "party-1", 3))
  assert(o:boarded(101, "party-2", 3))
  assert(o:deployed(101, "party-3", 3, true, true))
end)
test("airborne delivery cannot succeed", function()
  local o = aboard()
  assert(not o:deployed(101, "party-2", 3, true, false))
  assert(o.phase ~= "complete")
end)
test("wrong carrier rejected", function()
  local o = aboard()
  assert(not o:deployed(102, "party-2", 3, true, true))
  assert(o.phase == "aboard")
end)
test("aircraft replacement is terminal", function()
  local o = aboard()
  assert(not o:lock_carrier(102) and o.phase == "failed")
  assert(not o:deployed(101, "party-2", 3, true, true))
end)
test("loss cannot be reversed by delayed receipt", function()
  local o = aboard()
  assert(o:fail("lost"))
  assert(not o:boarded(101, "party-1", 3))
  assert(not o:deployed(101, "party-2", 3, true, true))
  assert(o.phase == "failed")
end)
test("partial party fails", function()
  local o = aboard()
  assert(not o:deployed(101, "party-2", 2, true, true))
  assert(o.phase == "failed")
end)
test("wrong pickup identity rejected", function()
  local o = Operation.new("party-1", 3)
  o:lock_carrier(101)
  o:begin_boarding(101)
  assert(not o:boarded(101, "unrelated", 3))
  assert(o.phase == "boarding")
end)
test("restarts inherit nothing", function()
  local old = aboard()
  old:deployed(101, "party-2", 3, true, true)
  local fresh = Operation.new("party-1", 3)
  assert(fresh.phase == "waiting" and not fresh.carrier_id)
end)
print("Hidden Passage operation: " .. count .. " checks passed")
